"""REPRODUCIBILITY CHECK (read-only on the data): run the Tableau Prep flow twice and on new data.

    python tools/check_reproducibility.py      (TabPy must be running: tools/run_tabpy_local.py)

Test 1 - same input, same flow, run twice -> every output must have the same fingerprint.
Test 2 - "new data": the flow is first run with only the 2009-2010 sheet (as if the second
         year had not arrived yet), then with both sheets. The 2009-2010 lines must get
         exactly the same quality decision (dq_status + dq_reason) in both runs.
Writes reports/reproducibility_check.md.
"""
import subprocess
from pathlib import Path

import pandas as pd

from verify_outputs import LINE_FILES, read, verify

ROOT = Path(__file__).resolve().parent.parent
RUN = ROOT / "tools" / "run_flow.sh"
KEY = ["invoice", "stock_code", "description", "quantity", "invoice_datetime", "unit_price_gbp", "customer_id"]


def run(flow):
    out = subprocess.run([str(RUN), str(ROOT / "prep" / flow)], capture_output=True, text=True).stdout
    if "Finished running the flow successfully" not in out:
        raise SystemExit(f"{flow} failed:\n{out}")


def decisions(out_dir):
    frames = [read(Path(out_dir) / f) for f in LINE_FILES]
    lines = pd.concat(frames, ignore_index=True)
    lines = lines[lines["source_sheet"].str.endswith("Year 2009-2010")]
    return lines[KEY + ["dq_status", "dq_reason"]].sort_values(KEY).reset_index(drop=True)


def main():
    out = ROOT / "data" / "output"
    run("online_retail_flow.tfl")
    first, _ = verify(out, ["Year 2009-2010", "Year 2010-2011"])
    run("online_retail_flow.tfl")
    second, _ = verify(out, ["Year 2009-2010", "Year 2010-2011"])

    lines = ["# Reproducibility check", "", "Generated by `tools/check_reproducibility.py`.", "",
             "## Test 1: the same flow on the same data, run twice", "",
             "| output | run 1 | run 2 | same? |", "|---|---|---|---|"]
    same_all = True
    for f, h in first["fingerprints"].items():
        same = second["fingerprints"][f] == h
        same_all &= same
        lines.append(f"| {f} | `{h[:12]}` | `{second['fingerprints'][f][:12]}` | {'yes' if same else 'NO'} |")
    lines += ["", f"**Result: {'identical' if same_all else 'DIFFERENT'}**", ""]

    small = ROOT / "data" / "output_first_year_only"
    for folder in (small, ROOT / "data" / "warehouse_first_year_only"):
        folder.mkdir(exist_ok=True)   # Prep does not create output folders itself
    run("online_retail_flow_first_year_only.tfl")
    verify(small, ["Year 2009-2010"])
    a, b = decisions(small), decisions(out)
    same_rows = len(a) == len(b) and a[KEY].equals(b[KEY])
    same_decisions = same_rows and a.equals(b)
    lines += ["## Test 2: new data arrives (first only 2009-2010, then both years)", "",
              "| | first year only | both years |", "|---|---|---|",
              f"| 2009-2010 lines | {len(a):,} | {len(b):,} |"]
    for s in ["trusted", "quarantine", "cancellation", "non_product"]:
        lines.append(f"| {s} | {(a['dq_status'] == s).sum():,} | {(b['dq_status'] == s).sum():,} |")
    lines += ["", f"Same 2009-2010 lines in both runs: **{'yes' if same_rows else 'NO'}**  ",
              f"Same quality decision for every line: **{'yes' if same_decisions else 'NO'}**", ""]
    (ROOT / "reports" / "reproducibility_check.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
