"""VERIFY (read-only): check what the Tableau Prep flow produced. Changes no data.

    python tools/verify_outputs.py                     # checks data/output/
    python tools/verify_outputs.py --out data/output_first_year_only

1. Reconciliation: raw rows = sum of 'copies' over the four line outputs
   (trusted + quarantine + cancellations + non-product). Nothing may disappear.
2. Quality KPIs AFTER cleaning (same formulas as profiling/profile_raw.py, BEFORE).
3. Fingerprint of every output: SHA-256 of its rows sorted, so the row order Tableau
   Prep happens to write does not matter. Two runs with equal fingerprints = same result.
Writes <out>/_manifest.json and reports/verification.md (for the main output).
"""
import argparse
import hashlib
import json
from pathlib import Path

import pandas as pd
from openpyxl import load_workbook

ROOT = Path(__file__).resolve().parent.parent
LINE_FILES = ["fact_sales.csv", "quarantine_lines.csv", "cancellations.csv", "non_product_lines.csv"]
ALL_FILES = LINE_FILES + ["monthly_revenue.csv", "customer_features.csv", "dim_product.csv"]


def read(path):
    return pd.read_csv(path, encoding="utf-8-sig", dtype=str, keep_default_na=False)


def fingerprint(df):
    """SHA-256 of the table with columns and rows sorted: independent of row order."""
    df = df[sorted(df.columns)].sort_values(sorted(df.columns)).reset_index(drop=True)
    return hashlib.sha256(df.to_csv(index=False, lineterminator="\n").encode()).hexdigest()


def raw_row_count(sheets):
    wb = load_workbook(ROOT / "data" / "raw" / "online_retail_II.xlsx", read_only=True)
    return {s: wb[s].max_row - 1 for s in sheets}  # minus the header row


def kpis_after(fact):
    """Completeness / duplication / validity of the trusted fact table."""
    core = ["invoice", "stock_code", "description", "quantity", "invoice_datetime", "unit_price_gbp", "country"]
    completeness = 100 * (fact[core] != "").to_numpy().mean()
    key = ["invoice", "stock_code", "description", "quantity", "invoice_datetime", "unit_price_gbp", "customer_id"]
    duplication = 100 * fact.duplicated(subset=key).mean()
    q, p = pd.to_numeric(fact["quantity"]), pd.to_numeric(fact["unit_price_gbp"])
    rules = [q > 0, p > 0, fact["invoice"].str.match(r"^\d{6}$"), fact["description"] != ""]
    validity = 100 * sum(int(r.sum()) for r in rules) / (len(fact) * len(rules))
    with_customer = 100 * (fact["customer_id"] != "").mean()
    return {"completeness_core_%": round(completeness, 2), "duplication_%": round(duplication, 2),
            "validity_4_rules_%": round(validity, 2), "lines_with_customer_%": round(with_customer, 2)}


def verify(out_dir, sheets):
    out_dir = Path(out_dir)
    tables = {f: read(out_dir / f) for f in ALL_FILES}
    raw = raw_row_count(sheets)
    copies = {f: int(pd.to_numeric(tables[f]["copies"]).sum()) for f in LINE_FILES}
    rows = {f: len(tables[f]) for f in LINE_FILES}
    manifest = {f: fingerprint(t) for f, t in tables.items()}
    result = {"raw_rows": raw, "raw_total": sum(raw.values()), "rows_per_output": rows,
              "copies_per_output": copies, "copies_total": sum(copies.values()),
              "duplicates_removed": sum(copies.values()) - sum(rows.values()),
              "balanced": sum(copies.values()) == sum(raw.values()),
              "kpis_after": kpis_after(tables["fact_sales.csv"]), "fingerprints": manifest}
    (out_dir / "_manifest.json").write_text(json.dumps(result, indent=2) + "\n")
    return result, tables


def report(result, tables):
    q = tables["quarantine_lines.csv"]["dq_reason"].value_counts()
    fact = tables["fact_sales.csv"]
    lines = ["# Verification of the Tableau Prep outputs", "",
             "Generated by `tools/verify_outputs.py` (read-only).", "",
             "## 1. Reconciliation: raw = trusted + quarantine + cancellations + non-product + duplicates", "",
             "| | rows |", "|---|---|"]
    for s, n in result["raw_rows"].items():
        lines.append(f"| raw sheet {s} | {n:,} |")
    lines.append(f"| **raw total** | **{result['raw_total']:,}** |")
    for f, n in result["rows_per_output"].items():
        lines.append(f"| {f} | {n:,} |")
    lines += [f"| duplicate rows removed | {result['duplicates_removed']:,} |",
              f"| **sum (copies)** | **{result['copies_total']:,}** |",
              f"| balanced? | **{'yes' if result['balanced'] else 'NO'}** |", "",
              "## 2. Quarantine reasons", "", "| reason | rows |", "|---|---|"]
    lines += [f"| {r} | {n:,} |" for r, n in q.items()]
    lines += ["", "## 3. Quality KPIs of the trusted fact table (after cleaning)", "", "| KPI | value |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in result["kpis_after"].items()]
    flags = (fact["price_outlier_iqr"] == "True").sum()
    unmatched = fact.loc[fact["country_matched"] == "False", "country_raw"].value_counts()
    lines += ["", f"Price outliers flagged (kept): **{flags:,}** lines.", "",
              "Countries without a match in the reference table: "
              + ", ".join(f"{c} ({n:,})" for c, n in unmatched.items()), "",
              "## 4. Fingerprints (SHA-256 of sorted rows)", "", "| file | sha256 |", "|---|---|"]
    lines += [f"| {f} | `{h[:16]}...` |" for f, h in result["fingerprints"].items()]
    (ROOT / "reports" / "verification.md").write_text("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=str(ROOT / "data" / "output"))
    parser.add_argument("--sheets", nargs="+", default=["Year 2009-2010", "Year 2010-2011"])
    args = parser.parse_args()
    result, tables = verify(args.out, args.sheets)
    if Path(args.out).resolve() == (ROOT / "data" / "output").resolve():
        report(result, tables)
    print(json.dumps({k: v for k, v in result.items() if k != "fingerprints"}, indent=2))


if __name__ == "__main__":
    main()
